# ---------- совпадающие с латиницей: глифы оригинала ----------
SAME_UPPER = {'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H',
              'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X'}
SAME_LOWER = {'а': 'a', 'е': 'e', 'к': 'k', 'о': 'o', 'р': 'p', 'с': 'c',
              'у': 'y', 'х': 'x'}

UPPER = 'АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ'
LOWER = 'абвгдежзийклмнопрстуфхцчшщъыьэюя'

def rows_to_bytes(rows):
    return bytes(int(r.replace('.', '0').replace('#', '1'), 2) for r in rows)

def build_font():
    orig = open(FONT_SRC, 'rb').read()
    assert len(orig) == 2048
    font = bytearray(orig)
    def put(ch, code):
        if ch in G:
            font[code*8:code*8+8] = rows_to_bytes(G[ch])
        else:
            latin = SAME_UPPER.get(ch) or SAME_LOWER.get(ch)
            assert latin, ch
            font[code*8:code*8+8] = orig[ord(latin)*8:ord(latin)*8+8]
    for i, ch in enumerate(UPPER):
        put(ch, 0x80 + i)          # 0x80-0x9F = А..Я
    for i in range(16):
        put(LOWER[i], 0xA0 + i)    # 0xA0-0xAF = а..п
    for i in range(16, 32):
        put(LOWER[i], 0xE0 + i - 16)   # 0xE0-0xEF = р..я (шрифт кончается на 0xEF!)
    # Ё/ё: слоты 0xF0+ вне шрифта — рендерим как Е/е (кодируется в textool)
    return bytes(font)

def render_grid(font, path, scale=3):
    img = Image.new('1', (16*8*scale, 16*8*scale))
    px = img.load()
    for code in range(256):
        gx = (code % 16) * 8 * scale
        gy = (code // 16) * 8 * scale
        for y in range(8):
            b = font[code*8+y]
            for x in range(8):
                if b & (0x80 >> x):
                    for dy in range(scale):
                        for dx in range(scale):
                            px[gx+x*scale+dx, gy+y*scale+dy] = 1
    img.save(path)

def render_text(font, lines, path, scale=3, pad=4):
    w = max(len(l) for l in lines) * 8
    h = len(lines) * 8
    img = Image.new('1', ((w + pad*2) * scale, (h + pad*2) * scale))
    px = img.load()
    for row, line in enumerate(lines):
        for col, ch in enumerate(line):
            code = game_encode(ch)[0]
            for y in range(8):
                b = font[code*8+y]
                for x in range(8):
                    if b & (0x80 >> x):
                        X = (pad + col*8 + x) * scale
                        Y = (pad + row*8 + y) * scale
                        for dy in range(scale):
                            for dx in range(scale):
                                px[X+dx, Y+dy] = 1
    img.save(path)

def render_text_prop(font, lines, path, scale=3, pad=4):
    # пропорциональный рендер: ширина глифа = крайний правый пиксель + 1px зазор
    widths = []
    for code in range(256):
        w = 0
        for y in range(8):
            b = font[code*8+y]
            for x in range(8):
                if b & (0x80 >> x):
                    w = max(w, x + 1)
        widths.append(w)
    def advance(ch):
        code = game_encode(ch)[0]
        if code == 0x20:
            return 4
        return widths[code] + 1
    total_w = sum(sum(advance(c) for c in l) for l in [max(lines, key=lambda l: sum(advance(c) for c in l))])
    h = len(lines) * 8
    img = Image.new('1', ((total_w + pad*2) * scale, (h + pad*2) * scale))
    px = img.load()
    for row, line in enumerate(lines):
        cx = 0
        for ch in line:
            code = game_encode(ch)[0]
            for y in range(8):
                b = font[code*8+y]
                for x in range(8):
                    if b & (0x80 >> x):
                        X = (pad + cx + x) * scale
                        Y = (pad + row*8 + y) * scale
                        for dy in range(scale):
                            for dx in range(scale):
                                px[X+dx, Y+dy] = 1
            cx += advance(ch)
    img.save(path)

